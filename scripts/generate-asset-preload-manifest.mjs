import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

export const GENERATED_ASSET_PRELOAD_MANIFEST_PATH =
  "src/game/phaser/generated/assetPreloadManifest.js";

export const PRELOADABLE_ASSET_KINDS_BY_EXTENSION = new Map([
  [".ani", "cursor"],
  [".css", "style"],
  [".cur", "cursor"],
  [".gif", "image"],
  [".jpeg", "image"],
  [".jpg", "image"],
  [".js", "script"],
  [".mjs", "script"],
  [".mp3", "audio"],
  [".ogg", "audio"],
  [".otf", "font"],
  [".png", "image"],
  [".svg", "image"],
  [".ttf", "font"],
  [".wav", "audio"],
  [".webp", "image"],
  [".woff", "font"],
  [".woff2", "font"],
]);

const PRELOAD_SCAN_ROOTS = [
  {
    directory: "assets",
    environment: "all",
  },
  {
    directory: "src",
    environment: "development",
    extensions: new Set([".css", ".js", ".mjs"]),
  },
];
const EXCLUDED_PRELOAD_RELATIVE_PATHS = new Set([
  GENERATED_ASSET_PRELOAD_MANIFEST_PATH,
]);
const PRODUCTION_RUNTIME_PRELOAD_ENTRIES = [
  {
    url: "./assets/main.css",
    kind: "style",
    byteSize: 1,
    environment: "production",
  },
  {
    url: "./assets/main.js",
    kind: "script",
    byteSize: 1,
    environment: "production",
  },
];

export async function generateAssetPreloadManifest({ root = process.cwd() } = {}) {
  const entries = await collectAssetPreloadEntries({ root });
  const totalBytes = entries.reduce((sum, entry) => sum + entry.byteSize, 0);
  const output = [
    "// This file is generated by scripts/generate-asset-preload-manifest.mjs.",
    "// Do not edit by hand.",
    `export const ASSET_PRELOAD_MANIFEST = ${JSON.stringify(entries, null, 2)};`,
    "",
    `export const ASSET_PRELOAD_TOTAL_BYTES = ${totalBytes};`,
    "",
  ].join("\n");
  const manifestPath = path.resolve(root, GENERATED_ASSET_PRELOAD_MANIFEST_PATH);

  await fs.mkdir(path.dirname(manifestPath), { recursive: true });
  await fs.writeFile(manifestPath, output, "utf8");

  return entries;
}

export async function collectAssetPreloadEntries({ root = process.cwd() } = {}) {
  const scannedEntries = await Promise.all(
    PRELOAD_SCAN_ROOTS.map(async (scanRoot) => {
      const directoryPath = path.resolve(root, scanRoot.directory);
      const filePaths = await collectPreloadableAssetFiles(directoryPath, {
        ...scanRoot,
        root,
      });

      return Promise.all(
        filePaths.map(async (filePath) => {
          const extension = path.extname(filePath).toLowerCase();
          const kind = PRELOADABLE_ASSET_KINDS_BY_EXTENSION.get(extension);
          const stat = await fs.stat(filePath);
          const relativePath = normalizeRelativePath(path.relative(root, filePath));
          const entry = {
            url: toStableAssetUrl(relativePath),
            kind,
            byteSize: stat.size,
          };

          if (scanRoot.environment !== "all") {
            entry.environment = scanRoot.environment;
          }

          return entry;
        }),
      );
    }),
  );
  const entries = [
    ...scannedEntries.flat(),
    ...PRODUCTION_RUNTIME_PRELOAD_ENTRIES,
  ];

  return entries.sort((left, right) => left.url.localeCompare(right.url));
}

async function collectPreloadableAssetFiles(directoryPath, scanRoot) {
  let directoryEntries = [];

  try {
    directoryEntries = await fs.readdir(directoryPath, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") {
      return [];
    }

    throw error;
  }

  const nestedEntries = await Promise.all(
    directoryEntries.map(async (entry) => {
      const entryPath = path.join(directoryPath, entry.name);

      if (entry.isDirectory()) {
        return collectPreloadableAssetFiles(entryPath, scanRoot);
      }

      if (!entry.isFile()) {
        return [];
      }

      const extension = path.extname(entry.name).toLowerCase();
      const relativePath = normalizeRelativePath(path.relative(scanRoot.root, entryPath));

      return PRELOADABLE_ASSET_KINDS_BY_EXTENSION.has(extension) &&
        !EXCLUDED_PRELOAD_RELATIVE_PATHS.has(relativePath) &&
        (!scanRoot.extensions || scanRoot.extensions.has(extension))
        ? [entryPath]
        : [];
    }),
  );

  return nestedEntries.flat();
}

function toStableAssetUrl(relativePath) {
  return `./${normalizeRelativePath(relativePath)
    .split("/")
    .join("/")
    .split("/")
    .map((part) => encodeURIComponent(part))
    .join("/")}`;
}

function normalizeRelativePath(relativePath) {
  return relativePath.split(path.sep).join("/");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateAssetPreloadManifest();
}
